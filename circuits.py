"""UCC-type circuits and the VQE energy function (exact Aer statevector).

Every expectation value is computed with Qiskit-Aer's ``EstimatorV2`` at its
default precision of 0, i.e. the exact statevector expectation value (no shot
noise).
"""

from functools import lru_cache

from qiskit import QuantumCircuit
from qiskit.transpiler.preset_passmanagers import generate_preset_pass_manager
from qiskit_aer import AerSimulator
from qiskit_aer.primitives import EstimatorV2 as Estimator
from qiskit_nature.second_q.circuit.library import UCC
from qiskit_nature.second_q.mappers import InterleavedQubitMapper, JordanWignerMapper

from .operators import reference_qubits


@lru_cache(maxsize=None)
def get_estimator():
    """One exact Aer estimator per process (it is stateless between runs)."""
    return Estimator()


@lru_cache(maxsize=None)
def get_pass_manager():
    """Level-3 preset pass manager targeting the Aer simulator (per process)."""
    return generate_preset_pass_manager(backend=AerSimulator(), optimization_level=3)


@lru_cache(maxsize=None)
def _mapper():
    return InterleavedQubitMapper(JordanWignerMapper())


def reference_circuit(n_qubits, n_electrons):
    """Mean-field reference state |phi_ref> as X gates."""
    qc = QuantumCircuit(n_qubits)
    qc.x(reference_qubits(n_qubits, n_electrons))
    return qc


def excitation_list(n_mo, n_particles, kind):
    """Excitations of type ``kind`` ('s', 'd', ...) generated by Qiskit-Nature."""
    return UCC(n_mo, n_particles, excitations=kind, qubit_mapper=_mapper()).excitation_list


def ucc_circuit(excitations, n_mo, n_particles, n_qubits, n_electrons):
    """Disentangled (product-of-exponentials) UCC circuit for the given
    excitation list, applied to the mean-field reference and transpiled.

    The first excitation of the list is the one acting first on the reference.
    """
    excitations = list(excitations)
    ansatz = UCC(n_mo, n_particles,
                 qubit_mapper=_mapper(),
                 initial_state=reference_circuit(n_qubits, n_electrons),
                 excitations=lambda num_spatial_orbitals, num_particles: excitations)
    return get_pass_manager().run(ansatz)


class EnergyFunction:
    """E(theta) = <psi(theta)| H |psi(theta)>, used as the VQE cost function.

    Picklable, so SciPy can send it to worker processes when the gradient is
    evaluated in parallel. ``nfev`` counts the evaluations made in *this*
    process.
    """

    def __init__(self, circuit, observable):
        self.circuit = circuit
        self.observable = observable
        self.nfev = 0
        self.last_params = None

    def __call__(self, params):
        self.nfev += 1
        self.last_params = params
        pub = (self.circuit, [self.observable], [params])
        return get_estimator().run(pubs=[pub]).result()[0].data.evs[0]

    def evaluate(self, params):
        """Single, uncounted energy evaluation (e.g. the starting energy)."""
        pub = (self.circuit, [self.observable], params)
        return get_estimator().run(pubs=[pub]).result()[0].data.evs[0]

    def __getstate__(self):
        return {"circuit": self.circuit, "observable": self.observable,
                "nfev": 0, "last_params": None}
